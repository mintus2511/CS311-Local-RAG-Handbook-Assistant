import os
from pathlib import Path

import streamlit as st

from app.chatbot import AcademicChatbot


PROJECT_ROOT = Path(__file__).resolve().parents[1]

st.set_page_config(
    page_title="Fulbright CS Handbook Assistant",
    page_icon="🎓",
    layout="centered"
)


@st.cache_resource(show_spinner="Loading handbook assistant...")
def load_chatbot():
    return AcademicChatbot(
        project_root=PROJECT_ROOT,
        ollama_base_url=os.getenv(
            "OLLAMA_BASE_URL",
            "http://127.0.0.1:11434"
        ),
        distance_threshold=float(
            os.getenv("DISTANCE_THRESHOLD", "0.60")
        )
    )


def show_sources(sources):
    if not sources:
        return

    with st.expander("View retrieved sources"):
        seen = set()

        for source in sources:
            filename = source.get(
                "source", "CS_MajorHandbook.pdf"
            )
            start = source.get("page")
            end = source.get("end_page", start)

            key = (filename, start, end)

            if key in seen:
                continue

            seen.add(key)

            if start is None:
                page_text = "Page unavailable"
            elif end is not None and end != start:
                page_text = f"PDF pages {start}–{end}"
            else:
                page_text = f"PDF page {start}"

            st.markdown(
                f"**{filename}** — {page_text}"
            )

            if source.get("section"):
                st.caption(
                    f"Section: {source['section']}"
                )

        st.caption(
            "These are retrieved source locations, "
            "not independently verified citations "
            "for every claim in the answer."
        )


def show_assistant_response(result):
    st.markdown(result["answer"])

    route_labels = {
        "course_lookup": "Course information lookup",
        "inverse_prerequisite": "Prerequisite relationship lookup",
        "general_rag": "Semantic RAG",
        "invalid_input": "Input validation",
    }

    route = route_labels.get(
        result["route"], result["route"]
    )

    st.caption(
        f"Method: {route} · "
        f"Response time: {result['elapsed']:.2f}s"
    )

    if result["grounding"] == "llm_generated_unverified":
        st.info(
            "This response was generated by a language "
            "model from retrieved handbook excerpts. "
            "Please verify important academic requirements."
        )

    if result["grounding"] == "abstained":
        st.warning(
            "The assistant could not establish sufficient "
            "evidence under its current retrieval policy."
        )

    show_sources(result.get("sources", []))


st.title("🎓 Fulbright CS Handbook Assistant")

st.caption(
    "Ask questions about the Computer Science major, "
    "minor, course prerequisites, and academic requirements."
)

with st.sidebar:
    st.header("About")
    st.write(
        "Document: Computer Science Major Handbook "
        "(Version 1.0, May 2025)"
    )

    st.write(
        "Retrieval: Structure-Aware ChromaDB "
        "+ Course Information Lookup"
    )

    st.write(
        "Language model: Qwen 2.5 0.5B via Ollama"
    )

    st.divider()

    st.subheader("Example questions")

    examples = [
        "What are the prerequisites for CS201?",
        "Which courses require CS201?",
        "How many credits are required for the CS major?",
        "What GPA is required to enroll in CS401 Capstone I?"
    ]

    for i, example in enumerate(examples):
        st.markdown(f"{i + 1}. {example}")

    st.divider()

    if st.button("Clear conversation", use_container_width=True):
        st.session_state.messages = []
        st.rerun()


if "messages" not in st.session_state:
    st.session_state.messages = []


for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        if message["role"] == "assistant":
            show_assistant_response(message["result"])
        else:
            st.markdown(message["content"])


prompt = st.chat_input(
    "Ask a question about the CS handbook..."
)

if prompt:
    st.session_state.messages.append({
        "role": "user",
        "content": prompt
    })

    with st.chat_message("user"):
        st.markdown(prompt)

    with st.chat_message("assistant"):
        try:
            chatbot = load_chatbot()

            with st.spinner("Searching the handbook..."):
                result = chatbot.ask(prompt)

            show_assistant_response(result)

        except Exception as exc:
            st.error(
                "Unable to complete the request. "
                "Check the Ollama server, model downloads, "
                "and ChromaDB configuration."
            )

            # Write the traceback to server logs rather
            # than displaying it in the chat interface.
            import logging
            logging.exception("Chatbot request failed")

        else:
            st.session_state.messages.append({
                "role": "assistant",
                "result": result
            })
